export const PROJECT_ICON_CATEGORIES: readonly string[] = CATEGORY_ICONS.map(([category]) => category);

export const PROJECT_ICONS: readonly ProjectIconEntry[] = CATEGORY_ICONS.flatMap(([category, items]) => items.map(([name, label, Icon]) => ({ name, label, category, Icon })));

const BY_NAME = new Map(PROJECT_ICONS.map((entry) => [entry.name, entry]));

export function projectIconByName(name: string): ProjectIconEntry | undefined {
  return BY_NAME.get(name);
}
