import { redactSecrets } from "./handoff.js";

/**
 * "Start fresh with summary": the first prompt of a new conversation, built deterministically (no model call) from the tail of
 * the previous provider transcript (live file or last-good checkpoint). Claude JSONL and Codex rollouts are understood; for any
 * other provider the caller does a plain fresh start.
 */

type Rec = Record<string, unknown>;
const isRec = (v: unknown): v is Rec => !!v && typeof v === "object" && !Array.isArray(v);

export const RESUME_SUMMARY_MAX_CHARS = 7_000;
const PROMPT_CHARS = 700;
const FIRST_PROMPT_CHARS = 900;
const REPLY_CHARS = 1_800;
const ACTION_CHARS = 140;
const MAX_PROMPTS = 3;
const MAX_ACTIONS = 12;
const MAX_FILES = 20;
const MAX_TODOS = 20;

export const RESUME_SUMMARY_PREFIX =
  "You are resuming work after your previous conversation could not be restored. Below is an automatic summary of where it left off, built from its transcript without a model. It may be incomplete: check the files and git state before continuing, and do not redo finished steps.";

export interface ResumeSummaryInput {
  provider: "claude" | "codex";
  /** Last part of the transcript (JSON lines); a partial first line is ignored. */
  tailText: string;
  /** First part of the transcript, for the original task (optional). */
  headText?: string;
  cwd?: string | null;
}

interface Extracted {
  firstPrompt: string | null;
  prompts: string[];
  reply: string | null;
  actions: string[];
  files: string[];
  todos: Array<{ status: string; content: string }>;
}

function parse(text: string): Rec[] {
  const out: Rec[] = [];
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim()) continue;
    try { const rec: unknown = JSON.parse(line); if (isRec(rec)) out.push(rec); } catch { /* partial or damaged line */ }
  }
  return out;
}

/** Obvious secrets first (shapes shorter than the generic 24-char rule), then the generic long-token scrubber. */
export function redactForSummary(text: string): string {
  const specific = text
    .replace(/-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]*?(-----END [A-Z ]*PRIVATE KEY-----|$)/g, "[redacted]")
    .replace(/\b(?:AKIA|ASIA)[0-9A-Z]{16}\b/g, "[redacted]")
    .replace(/\bgh[pousr]_[A-Za-z0-9]{16,}\b/g, "[redacted]")
    .replace(/\bgithub_pat_[A-Za-z0-9_]{16,}\b/g, "[redacted]")
    .replace(/\bsk-[A-Za-z0-9_-]{8,}/g, "[redacted]")
    .replace(/\bxox[abposr]-[A-Za-z0-9-]{8,}/g, "[redacted]")
    .replace(/\bAIza[0-9A-Za-z_-]{20,}\b/g, "[redacted]")
    .replace(/\b(Bearer|Basic)\s+[A-Za-z0-9._~+/=-]{8,}/gi, "$1 [redacted]")
    .replace(/\b([A-Za-z0-9_]*(?:SECRET|TOKEN|PASSWORD|PASSWD|API_?KEY|PRIVATE_?KEY|ACCESS_?KEY)[A-Za-z0-9_]*)\s*[=:]\s*("[^"\n]*"|'[^'\n]*'|[^\s"']+)/gi, "$1=[redacted]");
  return redactSecrets(specific);
}

const cut = (text: string, max: number) => (text.length > max ? text.slice(0, max) + " […]" : text);
const oneLine = (text: string) => text.replace(/\s+/g, " ").trim();
const fence = (text: string) => "```text\n" + text.replace(/```/g, "'''") + "\n```";

/** Skip Floq/CLI machinery messages that are not the user's words. */
function realPrompt(text: string): string | null {
  const t = text.trim();
  if (!t) return null;
  if (/^<(?:command-|local-command|system-reminder|user-prompt-submit-hook|environment_context|user_instructions|ide_)/i.test(t)) return null;
  if (t.startsWith("Caveat: The messages below were generated by the user while running local commands")) return null;
  return t;
}

function blocksOf(content: unknown): Rec[] {
  return Array.isArray(content) ? content.filter(isRec) : [];
}

function claudeAction(item: Rec, files: string[]): string | null {
  const name = typeof item.name === "string" ? item.name : "";
  const input = isRec(item.input) ? item.input : {};
  const path = typeof input.file_path === "string" ? input.file_path : typeof input.notebook_path === "string" ? input.notebook_path : null;
  switch (name) {
    case "Edit": case "MultiEdit": case "Write": case "NotebookEdit":
      if (path) files.push(path);
      return path ? `${name} ${path}` : name;
    case "Bash": return typeof input.command === "string" ? "Bash: " + oneLine(input.command) : "Bash";
    case "Task": case "Agent": return "Subagent: " + (typeof input.description === "string" ? oneLine(input.description) : "task");
    case "WebFetch": return typeof input.url === "string" ? "WebFetch " + input.url : "WebFetch";
    case "TodoWrite": case "Read": case "Grep": case "Glob": case "LS": return null; // reading is not progress
    default: return name ? name : null;
  }
}

function extractClaude(tail: Rec[], head: Rec[]): Extracted {
  const ex: Extracted = { firstPrompt: null, prompts: [], reply: null, actions: [], files: [], todos: [] };
  const userText = (rec: Rec): string | null => {
    if (rec.type !== "user" || rec.isSidechain === true || rec.isMeta === true || !isRec(rec.message)) return null;
    const c = rec.message.content;
    const text = typeof c === "string" ? c : blocksOf(c).filter((b) => b.type === "text" && typeof b.text === "string").map((b) => b.text as string).join("\n");
    return realPrompt(text);
  };
  for (const rec of head) { const p = userText(rec); if (p) { ex.firstPrompt = p; break; } }
  let replyId: string | null = null;
  for (const rec of tail) {
    if (rec.isSidechain === true) continue;
    const p = userText(rec);
    if (p) { ex.prompts.push(p); ex.reply = null; replyId = null; continue; }
    if (rec.type !== "assistant" || !isRec(rec.message) || rec.isApiErrorMessage === true) continue;
    const items = blocksOf(rec.message.content);
    const text = items.filter((b) => b.type === "text" && typeof b.text === "string").map((b) => b.text as string).join("");
    if (text.trim()) {
      const id = typeof rec.message.id === "string" ? rec.message.id : null;
      ex.reply = id !== null && id === replyId && ex.reply ? ex.reply + text : text;
      replyId = id;
    }
    for (const item of items) {
      if (item.type !== "tool_use") continue;
      if (item.name === "TodoWrite" && isRec(item.input) && Array.isArray(item.input.todos)) {
        ex.todos = item.input.todos.filter(isRec).filter((t) => typeof t.content === "string").map((t) => ({ status: typeof t.status === "string" ? t.status : "pending", content: t.content as string }));
        continue;
      }
      const action = claudeAction(item, ex.files);
      if (action) ex.actions.push(action);
    }
  }
  return ex;
}

function codexUserText(rec: Rec): string | null {
  const payload = isRec(rec.payload) ? rec.payload : null;
  if (rec.type !== "event_msg" || !payload || payload.type !== "user_message" || typeof payload.message !== "string") return null;
  return realPrompt(payload.message);
}

function extractCodex(tail: Rec[], head: Rec[]): Extracted {
  const ex: Extracted = { firstPrompt: null, prompts: [], reply: null, actions: [], files: [], todos: [] };
  for (const rec of head) { const p = codexUserText(rec); if (p) { ex.firstPrompt = p; break; } }
  for (const rec of tail) {
    const payload = isRec(rec.payload) ? rec.payload : null;
    if (!payload) continue;
    const p = codexUserText(rec);
    if (p) { ex.prompts.push(p); ex.reply = null; continue; }
    if (rec.type === "event_msg") {
      if (payload.type === "agent_message" && typeof payload.message === "string" && payload.message.trim()) ex.reply = payload.message;
      else if (payload.type === "task_complete" && typeof payload.last_agent_message === "string" && payload.last_agent_message.trim()) ex.reply = payload.last_agent_message;
      continue;
    }
    if (rec.type !== "response_item") continue;
    if (payload.type === "function_call") {
      const name = typeof payload.name === "string" ? payload.name : "";
      let args: Rec = {};
      try { const a: unknown = JSON.parse(typeof payload.arguments === "string" ? payload.arguments : "{}"); if (isRec(a)) args = a; } catch { /* keep empty */ }
      if (name === "update_plan" && Array.isArray(args.plan)) {
        ex.todos = args.plan.filter(isRec).filter((t) => typeof t.step === "string").map((t) => ({ status: typeof t.status === "string" ? t.status : "pending", content: t.step as string }));
      } else {
        const cmd = Array.isArray(args.command) ? args.command.filter((c) => typeof c === "string").join(" ") : typeof args.command === "string" ? args.command : typeof args.cmd === "string" ? args.cmd : "";
        if (cmd) ex.actions.push("Shell: " + oneLine(cmd));
        else if (name) ex.actions.push(name);
      }
    } else if (payload.type === "custom_tool_call" && payload.name === "apply_patch" && typeof payload.input === "string") {
      const touched = [...payload.input.matchAll(/^\*\*\* (?:Add|Update|Delete) File: (.+)$/gm)].map((m) => m[1]!.trim());
      for (const f of touched) { ex.files.push(f); ex.actions.push("apply_patch " + f); }
    }
  }
  return ex;
}

/** Newest-first de-duplication keeping the most recent occurrences, returned oldest to newest. */
function lastUnique(items: string[], max: number): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (let i = items.length - 1; i >= 0 && out.length < max; i--) {
    const item = items[i]!;
    if (seen.has(item)) continue;
    seen.add(item);
    out.push(item);
  }
  return out.reverse();
}

/** The handoff prompt, or null when the transcript holds nothing worth carrying over. Never longer than RESUME_SUMMARY_MAX_CHARS. */
export function buildResumeSummary(input: ResumeSummaryInput): string | null {
  const tail = parse(input.tailText);
  const head = input.headText ? parse(input.headText) : [];
  const ex = input.provider === "claude" ? extractClaude(tail, head) : extractCodex(tail, head);
  const firstPrompt = ex.firstPrompt ?? ex.prompts[0] ?? null;
  if (!firstPrompt && !ex.prompts.length && !ex.reply) return null;

  const sections: string[] = [];
  if (input.cwd) sections.push(`Working directory: ${input.cwd}`);
  if (firstPrompt) sections.push("## Original task\n" + fence(cut(firstPrompt, FIRST_PROMPT_CHARS)));
  const recent = ex.prompts.slice(-MAX_PROMPTS);
  if (recent.length) sections.push("## Latest requests from the user\n" + recent.map((p, i) => `${i + 1}. ${cut(oneLine(p), PROMPT_CHARS)}`).join("\n"));
  const todos = ex.todos.slice(0, MAX_TODOS);
  if (todos.length) sections.push("## Todo list at the time\n" + todos.map((t) => `- [${t.status === "completed" ? "x" : t.status === "in_progress" ? "~" : " "}] ${cut(oneLine(t.content), 160)}`).join("\n"));
  const files = lastUnique(ex.files, MAX_FILES);
  if (files.length) sections.push("## Files edited recently\n" + files.map((f) => "- " + f).join("\n"));
  const actions = lastUnique(ex.actions, MAX_ACTIONS);
  if (actions.length) sections.push("## Recent actions (oldest first)\n" + actions.map((a) => "- " + cut(a, ACTION_CHARS)).join("\n"));
  if (ex.reply) sections.push("## Your last reply\n" + fence(cut(ex.reply.trim(), REPLY_CHARS)));
  sections.push("Continue from here. If the next step is unclear, say what you understand and ask.");

  const body = redactForSummary(sections.join("\n\n"));
  const text = RESUME_SUMMARY_PREFIX + "\n\n" + body;
  return text.length > RESUME_SUMMARY_MAX_CHARS ? text.slice(0, RESUME_SUMMARY_MAX_CHARS - 40) + "\n[summary cut at the size limit]" : text;
}
